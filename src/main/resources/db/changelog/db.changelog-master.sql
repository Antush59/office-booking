--changeset office-booking:001-create-rooms
CREATE TABLE rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    capacity INT NOT NULL
);

--changeset office-booking:002-create-bookings
CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL,
    user_name VARCHAR(255) NOT NULL,
    start_at TIMESTAMP NOT NULL,
    end_at TIMESTAMP NOT NULL,
    status VARCHAR(32) NOT NULL,
    CONSTRAINT fk_bookings_room FOREIGN KEY (room_id) REFERENCES rooms(id)
);

CREATE INDEX idx_bookings_room_start ON bookings (room_id, start_at);

--changeset office-booking:003-add-bookings-status-check
ALTER TABLE bookings ADD CONSTRAINT chk_bookings_status CHECK (status IN ('ACTIVE', 'CANCELLED'));
